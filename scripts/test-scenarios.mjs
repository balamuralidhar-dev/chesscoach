import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { Chess } from 'chess.js';
import { DEFAULT_POSITION, positionFen, piecesFromFen, validateScenario, enginePosition, SCENARIO_PRESETS } from '../src/scenarios.js';
for(const preset of SCENARIO_PRESETS)assert.equal(validateScenario(preset.fen),new Chess(preset.fen).fen());
assert.equal(positionFen(piecesFromFen(DEFAULT_POSITION)).split(' ')[0],DEFAULT_POSITION.split(' ')[0]);
assert.throws(()=>validateScenario('8/8/8/8/8/8/8/8 w - - 0 1'));
assert.throws(()=>validateScenario('8/8/8/8/8/8/4k3/4K3 w - - 0 1'));
assert.throws(()=>validateScenario('7k/6Q1/5K2/8/8/8/8/8 b - - 0 1'));
const fen='8/5pk1/6p1/8/8/6P1/5PK1/R6r b - - 0 15';
const game=new Chess(validateScenario(fen));
assert.equal(enginePosition(fen,[]),`position fen ${fen}`);
const first=game.moves({verbose:true})[0];game.move(first.san);assert(enginePosition(fen,game.history({verbose:true})).endsWith(` moves ${first.from}${first.to}`));
assert.equal(game.history({verbose:true})[0].before.split(' ')[5],'15');
console.log('PASS: scenario presets, FEN roundtrip, invalid kings, terminal positions, Black-to-move and engine history commands.');
const child=spawn(process.execPath,['node_modules/stockfish/bin/stockfish-19-lite-single.js']);
let buffer='',requested=false,finished=false;
const timeout=setTimeout(()=>{child.kill();process.exitCode=1;console.error('Stockfish timed out.');},15000);
child.stdout.on('data',chunk=>{buffer+=chunk;if(buffer.includes('uciok') && !requested){requested=true;child.stdin.write(`isready\n${enginePosition(fen,[])}\ngo movetime 150\n`);}const match=buffer.match(/bestmove ([a-h][1-8][a-h][1-8][qrbn]?)/);if(match && !finished){finished=true;try{const position=new Chess(fen);position.move({from:match[1].slice(0,2),to:match[1].slice(2,4),promotion:match[1][4] || 'q'});console.log(`PASS: real Stockfish returned legal scenario move ${match[1]}.`);}catch(e){console.error(e.message);process.exitCode=1;}clearTimeout(timeout);child.kill();}});
child.on('error',error=>{clearTimeout(timeout);console.error(error.message);process.exitCode=1;});
child.stdin.write('uci\n');
